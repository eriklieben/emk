// semantic-release configuration. A push to main whose checks pass (release.yml: ci.yml, then the firmware and
// kbnotify builds) looks at the commits since the last release tag and, when one of them is a feat / fix / perf /
// revert (or a breaking change), releases the next version: the firmware for both halves (.uf2) and kbnotify for
// Linux and Windows on a GitHub release v<version>, the tag, and CHANGELOG.md (only with the GitHub App, see below).
// How to write the commits: docs/development.md, "Commit messages". How a release works: docs/releasing.md.
//
//   GITHUB_TOKEN=$(gh auth token) pnpm exec semantic-release --dry-run --no-ci     what would the next release be?
//
// Commits not in this format have no type: the analyzer ignores them, so they never release anything and aren't in
// the notes.

// The Angular commit format (type(scope): subject), plus the `!` breaking-change marker from Conventional Commits
// (`feat!: ...`, `fix(ble)!: ...`). Same as the conventionalcommits preset's parser, plus the plural `BREAKING CHANGES`
// footer that the Angular guidelines also allow. Shared by the analyzer and the notes generator so both see the same
// commits.
const parserOpts = {
  headerPattern: /^(\w*)(?:\((.*)\))?!?: (.*)$/,
  breakingHeaderPattern: /^(\w*)(?:\((.*)\))?!: (.*)$/,
  headerCorrespondence: ["type", "scope", "subject"],
  noteKeywords: ["BREAKING CHANGE", "BREAKING CHANGES", "BREAKING-CHANGE"],
};

// Release-notes sections (conventional-changelog-conventionalcommits; the first matching entry wins, so the `deps`
// entries come before plain `fix` / `build`). Every release is a `##` heading, breaking changes get their own
// "⚠ BREAKING CHANGES" section and scopes are shown in bold (`**display:** add a battery screen`). Hidden types don't
// appear in the notes (they don't release anything either, see the analyzer below), unless they carry a breaking
// change. Dependency updates: fix(deps) (shipped in the firmware or kbnotify, releases a patch) or build(deps) (build
// tooling: no release, but listed when something else releases); build(deps-dev) stays hidden.
const presetConfig = {
  types: [
    { type: "feat", section: "Features" },
    { type: "fix", scope: "deps", section: "Dependencies" },
    { type: "build", scope: "deps", section: "Dependencies" },
    { type: "fix", section: "Bug Fixes" },
    { type: "perf", section: "Performance" },
    { type: "revert", section: "Reverts" },
    { type: "docs", section: "Documentation", hidden: true },
    { type: "style", section: "Styles", hidden: true },
    { type: "chore", section: "Miscellaneous", hidden: true },
    { type: "refactor", section: "Refactoring", hidden: true },
    { type: "test", section: "Tests", hidden: true },
    { type: "build", section: "Build", hidden: true },
    { type: "ci", section: "CI", hidden: true },
  ],
};
// The preset orders sections by their first entry in `types`, which would put Dependencies above Bug Fixes.
const sectionOrder = ["Features", "Bug Fixes", "Performance", "Reverts", "Dependencies"];
const rank = (title) => (sectionOrder.includes(title) ? sectionOrder.indexOf(title) : sectionOrder.length);
const writerOpts = { commitGroupsSort: (a, b) => rank(a.title) - rank(b.title) };

// Kept at the top of CHANGELOG.md; @semantic-release/changelog adds each release below it. Must match the file.
const changelogTitle = `# Changelog

All notable changes to EMK are documented here. This file is generated by
[semantic-release](https://github.com/semantic-release/semantic-release) from the commit messages (see
[docs/development.md](docs/development.md#commit-messages)): don't edit it by hand, write a good commit message
instead. Versions follow [Semantic Versioning](https://semver.org/spec/v2.0.0.html).`;

// EMK_RELEASE_COMMIT=api: set by release.yml when the token of the emk-release GitHub App (variable RELEASE_APP_ID,
// environment secret RELEASE_APP_PRIVATE_KEY) was made. Then CHANGELOG.md is updated and committed through the GitHub
// API by eng/release-commit.mjs: GitHub signs that commit ("Verified", author emk-release[bot]), and the tag goes on
// it. Without the App (and in local dry runs) there is no release commit at all, never an unverified push: main
// requires signed commits, so @semantic-release/git's `git push` would be refused. The tag then goes on the released
// commit itself and the notes are only on the GitHub release. EMK has no version in its source to bump, so
// CHANGELOG.md is the only file a release commits.
const withReleaseCommit = process.env.EMK_RELEASE_COMMIT === "api";
const releaseCommit = withReleaseCommit
  ? [
      ["@semantic-release/changelog", { changelogFile: "CHANGELOG.md", changelogTitle }],
      [
        "./eng/release-commit.mjs",
        { assets: ["CHANGELOG.md"], message: "chore(release): ${nextRelease.version} [skip ci]\n\n${nextRelease.notes}" },
      ],
    ]
  : [];

export default {
  // main releases normal versions (1.2.3). next and beta are optional prerelease branches (1.3.0-beta.1, ...: GitHub
  // prereleases; create them when needed, see docs/releasing.md, "Prereleases"). release.yml runs on main only, so add
  // the branch to its `on.push.branches` too before using one.
  branches: [
    "main",
    { name: "next", prerelease: true },
    { name: "beta", prerelease: true },
  ],
  tagFormat: "v${version}",
  plugins: [
    [
      "@semantic-release/commit-analyzer",
      {
        preset: "conventionalcommits",
        presetConfig,
        parserOpts,
        // The analyzer's defaults: a breaking change -> major, feat -> minor, fix / perf / revert -> patch; docs, chore,
        // refactor, test, ci, build and style -> no release, whatever their scope.
      },
    ],
    [
      "@semantic-release/release-notes-generator",
      {
        preset: "conventionalcommits",
        presetConfig,
        parserOpts,
        writerOpts,
      },
    ],
    ...releaseCommit,
    [
      "@semantic-release/github",
      {
        // dist/ is filled by release.yml from the firmware and kbnotify jobs' artifacts.
        assets: [
          { path: "dist/fw-nrf-left-ble-erik_kbd.uf2", label: "Firmware, left half (erik_kbd, .uf2)" },
          { path: "dist/fw-nrf-right-ble-erik_kbd.uf2", label: "Firmware, right half (erik_kbd, .uf2)" },
          { path: "dist/kbnotify-linux-x64", label: "kbnotify for Linux (x64)" },
          { path: "dist/kbnotify-win-x64.exe", label: "kbnotify for Windows (x64)" },
          { path: "dist/SHA256SUMS", label: "SHA256SUMS" },
        ],
        // Defaults kept: released pull requests and issues get a comment and the label `released`, and a failed
        // release opens one issue ("The automated release is failing") that the next successful release closes. Set
        // successComment / failComment to false here if that gets noisy.
      },
    ],
  ],
};
